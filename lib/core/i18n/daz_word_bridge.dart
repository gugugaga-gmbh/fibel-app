/// Interactive pill widget that shows & speaks the heritage-language translation
/// of [germanWord] when the active child profile has a `BridgeLanguage` enabled.
class DazWordBridgeChip extends ConsumerWidget {
  final String germanWord;
  final bool compact;

  const DazWordBridgeChip({
    super.key,
    required this.germanWord,
    this.compact = false,
  });

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final bridgeLang = ref.watch(progressProvider).effectiveBridgeLanguage;
    if (!bridgeLang.isEnabled) {
      return const SizedBox.shrink();
    }
    final translated = DazWordBridge.translate(germanWord, bridgeLang);
    if (translated == null || translated.isEmpty) {
      return const SizedBox.shrink();
    }

    return Padding(
      padding: EdgeInsets.only(top: compact ? 4 : 8),
      child: InkWell(
        borderRadius: BorderRadius.circular(14),
        onTap: () => ref
            .read(audioServiceProvider)
            .speakBridgeWord(translated, bridgeLang),
        child: Container(
          padding: EdgeInsets.symmetric(
            horizontal: compact ? 8 : 12,
            vertical: compact ? 3 : 6,
          ),
          decoration: BoxDecoration(
            color: AppColors.owlTeal.withValues(alpha: 0.12),
            borderRadius: BorderRadius.circular(14),
            border: Border.all(
              color: AppColors.owlTeal.withValues(alpha: 0.4),
            ),
          ),
          child: Row(
            mainAxisSize: MainAxisSize.min,
            children: [
              Text(
                bridgeLang.flagEmoji,
                style: TextStyle(fontSize: compact ? 13 : 16),
              ),
              const SizedBox(width: 6),
              Flexible(
                child: Text(
                  translated,
                  maxLines: 1,
                  overflow: TextOverflow.ellipsis,
                  textDirection: bridgeLang.isRtl
                      ? TextDirection.rtl
                      : TextDirection.ltr,
                  style: TextStyle(
                    fontSize: compact ? 12 : 15,
                    fontWeight: FontWeight.w700,
                    color: AppColors.owlTeal,
                  ),
                ),
              ),
              const SizedBox(width: 5),
              Icon(
                Icons.volume_up_rounded,
                size: compact ? 14 : 17,
                color: AppColors.owlTeal,
              ),
            ],
          ),
        ),
      ),
    );
  }
}
